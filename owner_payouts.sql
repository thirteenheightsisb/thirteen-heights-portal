-- ---------- 1. Owner details on each flat ----------
alter table public.flats add column if not exists owner_name           text;
alter table public.flats add column if not exists owner_phone          text;
alter table public.flats add column if not exists owner_account        text;   -- bank / IBAN / JazzCash details
alter table public.flats add column if not exists owner_monthly_amount numeric(12,2) not null default 0;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'flats_owner_monthly_amount_check') then
    alter table public.flats
      add constraint flats_owner_monthly_amount_check check (owner_monthly_amount >= 0);
  end if;
end $$;

-- ---------- 2. Money paid out to flat owners ----------
create table if not exists public.owner_payouts (
  id               uuid primary key default gen_random_uuid(),
  payout_no        bigint generated by default as identity unique,
  flat_id          uuid references public.flats (id) on delete set null,
  owner_name       text,                                   -- kept even if the flat is deleted
  period           date not null,                          -- always the 1st of the month it is for
  amount           numeric(12,2) not null check (amount > 0),
  paid_on          date not null default current_date,
  method           text not null default 'Bank transfer',
  paid_to_account  text,                                   -- account the money went into
  reference        text,                                   -- transaction ID / cheque no.
  note             text,                                   -- any other details
  created_by       uuid default auth.uid(),
  created_at       timestamptz not null default now()
);
create index if not exists owner_payouts_flat_idx   on public.owner_payouts (flat_id);
create index if not exists owner_payouts_period_idx on public.owner_payouts (period);

-- ---------- 3. Activity log ----------
drop trigger if exists log_owner_payouts on public.owner_payouts;
create trigger log_owner_payouts after insert or update or delete on public.owner_payouts
  for each row execute function public.log_activity();

-- ---------- 4. Security: approved users can see/add/edit, only admins can delete ----------
alter table public.owner_payouts enable row level security;

drop policy if exists "read owner_payouts"   on public.owner_payouts;
drop policy if exists "add owner_payouts"    on public.owner_payouts;
drop policy if exists "edit owner_payouts"   on public.owner_payouts;
drop policy if exists "delete owner_payouts" on public.owner_payouts;
create policy "read owner_payouts"   on public.owner_payouts for select to authenticated using (public.is_approved());
create policy "add owner_payouts"    on public.owner_payouts for insert to authenticated with check (public.is_approved());
create policy "edit owner_payouts"   on public.owner_payouts for update to authenticated using (public.is_approved()) with check (public.is_approved());
create policy "delete owner_payouts" on public.owner_payouts for delete to authenticated using (public.is_admin());

grant select, insert, update, delete on public.owner_payouts to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Refresh the flats view so it also shows the new owner columns
drop view if exists public.flats_overview;
create view public.flats_overview with (security_invoker = true) as
select
  f.*,
  r.id        as resident_id,
  r.full_name as resident_name,
  r.phone     as resident_phone,
  case when r.id is null then 'vacant' else 'occupied' end as occupancy
from public.flats f
left join public.residents r on r.flat_id = f.id and r.status = 'active';
grant select on public.flats_overview to authenticated;

